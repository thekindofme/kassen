"""Scan assets/audio and write scripts/audio/audio_bank.gd (sound name -> variant paths)."""
import os, re, glob
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, '..', '..', '..'))
groups = {}
for p in sorted(glob.glob(os.path.join(ROOT, 'assets', 'audio', '**', '*.ogg'), recursive=True)):
    base = os.path.splitext(os.path.basename(p))[0]
    name = re.sub(r'_\d\d$', '', base)
    if base.startswith('wind_plain') or base.startswith('birds_loop') or base.startswith('river_loop'):
        name = 'amb_' + base.split('_')[0]
    rel = 'res://' + os.path.relpath(p, ROOT).replace(os.sep, '/')
    groups.setdefault(name, []).append(rel)
lines = ['extends RefCounted', '## Generated by art_src/audio_dl/synth/gen_bank.py: sound name -> variant files.',
         '## Regenerate after adding/removing files in assets/audio.', '', 'const FILES := {']
for k in sorted(groups):
    lines.append(f'\t"{k}": [' + ', '.join(f'"{v}"' for v in groups[k]) + '],')
lines.append('}')
open(os.path.join(ROOT, 'scripts', 'audio', 'audio_bank.gd'), 'w').write('\n'.join(lines) + '\n')
print(len(groups), 'sounds,', sum(len(v) for v in groups.values()), 'files')
